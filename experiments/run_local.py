"""Deterministic synthetic contract mutation study, not research-artifact reruns.

Uses the actual pinned use-hpc validator as a comparator. No GPU, Slurm, model,
queue-time or saved-compute measurements are generated by this experiment.
"""
import argparse
import copy
import csv
import hashlib
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from resai.core import digest, readiness, refine
from resai.pipeline import load_engine

FAULTS = ["clean", "missing_gpu", "bad_dependency", "runtime_failure", "missing_probe", "malformed_output", "stale_identity", "stale_time", "oom", "unstable_memory", "over_budget", "duplicate_attempt", "missing_accounting"]
CONDITIONS = ["direct", "upstream_static", "upstream_smoke", "resai"]


def fixture(seed=0):
    rng = random.Random(seed)
    plan = {"scientific": {"model": "synthetic-model", "data_sha256": digest([seed]), "batch_invariant": True},
            "execution": {"nodes": 1, "gpus_per_node": 1, "batch_size": 8, "wall_seconds": 900, "partition": "fixture"},
            "required_probes": ["imports", "model_init", "boundary_input", "output", "checkpoint"],
            "budget_gpu_seconds": 1200, "max_attempts": 4, "memory_limit": 0.9,
            "stability_epsilon": 0.05, "evidence_ttl_seconds": 3600}
    ratio = rng.uniform(0.4, 0.7)
    evidence = {"attempts": [{"attempt_id": str(i), "plan_hash": digest(plan), "timestamp": 10000+i,
        "status": "ok", "passed_probes": plan["required_probes"][:], "output_valid": True,
        "output_exists": True, "peak_memory_fraction": ratio + i*0.01, "gpu_seconds": 60} for i in range(2)]}
    graph = {"require_gpu": True, "stages": [{"name": "setup", "resources": {"gpus": "fixture:1"},
             "steps": [{"name": "run", "cmd": "echo fixture"}]}]}
    return plan, evidence, graph


def mutate(fault, plan, evidence, graph):
    last = evidence["attempts"][-1]
    if fault == "missing_gpu":
        graph["stages"][0]["resources"] = {}
    elif fault == "bad_dependency":
        graph["stages"][0]["depends"] = [{"stage": "nonexistent", "type": "afterok"}]
    elif fault == "runtime_failure":
        last["status"] = "failed"
    elif fault == "missing_probe":
        last["passed_probes"].remove("checkpoint")
    elif fault == "malformed_output":
        last["output_valid"] = False
    elif fault == "stale_identity":
        plan["scientific"]["model"] = "changed-model"
    elif fault == "stale_time":
        last["timestamp"] = 1
    elif fault == "oom":
        last.update(peak_memory_fraction=0.98, fault="oom")
    elif fault == "unstable_memory":
        last["peak_memory_fraction"] += 0.12
    elif fault == "over_budget":
        last["gpu_seconds"] = 1300
    elif fault == "duplicate_attempt":
        last["attempt_id"] = evidence["attempts"][0]["attempt_id"]
    elif fault == "missing_accounting":
        del last["gpu_seconds"]


def run(out, seeds):
    out.mkdir(parents=True, exist_ok=True)
    engine = load_engine()
    rows = []
    for seed in range(seeds):
        for fault in FAULTS:
            plan, evidence, graph = fixture(seed)
            mutate(fault, plan, evidence, graph)
            static_ok = not engine.validate(engine.resolve(graph, False))
            smoke_ok = all(x["status"] == "ok" and x["output_exists"] for x in evidence["attempts"])
            gate = readiness(plan, evidence, now=10010)
            decisions = [True, static_ok, static_ok and smoke_ok, static_ok and gate["ready"]]
            for condition, admitted in zip(CONDITIONS, decisions):
                rows.append({"seed": seed, "fault": fault, "condition": condition,
                             "admitted": int(admitted), "expected_admit": int(fault == "clean"),
                             "correct": int(admitted == (fault == "clean")), "plan_hash": digest(plan)})
    with (out / "decisions.csv").open("w", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    summary = {"evidence_type": "synthetic contract mutation", "seeds": seeds, "fault_families": len(FAULTS)-1,
               "cases_per_condition": seeds*len(FAULTS), "decisions": len(rows), "conditions": {}}
    for condition in CONDITIONS:
        subset = [r for r in rows if r["condition"] == condition]
        faults = [r for r in subset if r["fault"] != "clean"]
        clean = [r for r in subset if r["fault"] == "clean"]
        summary["conditions"][condition] = {"blocked_faults": sum(not r["admitted"] for r in faults),
            "fault_cases": len(faults), "false_blocks": sum(not r["admitted"] for r in clean), "clean_cases": len(clean)}
    (out / "summary.json").write_text(json.dumps(summary, indent=2)+"\n")
    manifest = {"python": sys.version, "seed_range": [0, seeds-1], "upstream_commit": "f9dc7d66ad8df3c202f6b72b02630e14fd148756",
        "sources": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in
            [Path(__file__), ROOT/"src/resai/core.py", ROOT/"hpc/scripts/hpclib.py"]}}
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2)+"\n")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=ROOT/"experiments/results/local")
    parser.add_argument("--seeds", type=int, default=20)
    args = parser.parse_args()
    if args.seeds <= 0:
        parser.error("seeds must be positive")
    run(args.out, args.seeds)
